"""daily_crawler

Automatically generated by Colab.

# 專題核心模組：每日歷史新聞增量爬蟲與情緒量化
本筆記本負責每日自動抓取五大權值股之最新財經新聞，並透過預訓練之 NLP 模型進行多空情緒打分。
為防範前視偏誤（Look-Ahead Bias），本模組內建 13:30 收盤時間切分規則，確保盤後新聞遞延。
並已修正：時區對齊、週末順延機制、長榮相關雜訊過濾。
"""

import requests
import pandas as pd
from datetime import datetime, timedelta
import time
import os
import pytz # 新增 pytz 處理時區
import torch
from transformers import BertTokenizer, BertForSequenceClassification

# 設定統一時區為台北
taipei_tz = pytz.timezone('Asia/Taipei')

# 目標五檔個股
TARGET_STOCKS = {'2330': '台積電', '2317': '鴻海', '2603': '長榮', '2002': '中鋼', '2891': '中信金'}
CSV_FILE = 'sentiment_features_2026.csv'

print("📥 載入 FinBERT-Chinese 模型...")
tokenizer = BertTokenizer.from_pretrained('IDEA-CCNL/Erlangshen-Roberta-110M-Sentiment')
model = BertForSequenceClassification.from_pretrained('IDEA-CCNL/Erlangshen-Roberta-110M-Sentiment')

def get_finbert_score(text):
    """計算新聞情緒分數"""
    if not text: return 0.0
    inputs = tokenizer(text, return_tensors="pt", truncation=True, max_length=256)
    with torch.no_grad():
        outputs = model(**inputs)
        probs = torch.nn.functional.softmax(outputs.logits, dim=-1)
        score = probs[0][1].item() - probs[0][0].item()
    return round(score, 4)

def fetch_today_news():
    """抓取今日新聞，並明確使用 Asia/Taipei 時區"""
    url = 'https://api.cnyes.com/media/api/v1/newslist/category/tw_stock'
    headers = {'User-Agent': 'Mozilla/5.0'}

    today = datetime.now(taipei_tz)
    # 計算今日凌晨 00:00 到現在的時間戳記
    start_dt = today.replace(hour=0, minute=0, second=0, microsecond=0)
    start_ts = int(start_dt.timestamp())
    end_ts = int(today.timestamp())

    daily_news = []
    for page in range(1, 10):
        params = {'limit': 30, 'page': page, 'startAt': start_ts, 'endAt': end_ts}
        try:
            res = requests.get(url, headers=headers, params=params, timeout=10)
            if res.status_code != 200: break
            items = res.json().get('items', {}).get('data', [])
            if not items: break

            for item in items:
                daily_news.append({
                    # 明確轉換為台北時區
                    'publish_time': datetime.fromtimestamp(item.get('publishAt'), taipei_tz),
                    'title': str(item.get('title') or '').strip(),
                    'summary': str(item.get('summary') or '').strip(),
                })
            time.sleep(0.5)
        except Exception as e:
            print("爬蟲異常:", e)
            break
    return daily_news

def align_trading_date(publish_time):
    """精準時間對齊：13:30 切分 + 週末順延至下個交易日(週一)"""
    cutoff_time = datetime.strptime('13:30:00', '%H:%M:%S').time()

    # 大於 13:30 算隔天
    if publish_time.time() > cutoff_time:
        target_date = publish_time.date() + timedelta(days=1)
    else:
        target_date = publish_time.date()

    # 週末假日過濾：5代表週六，6代表週日，遇到週末則自動順延至週一
    while target_date.weekday() >= 5:
        target_date += timedelta(days=1)

    return target_date

def is_target_news(title, summary, code, name):
    """精準公司名稱辨識函數：排除同名雜訊"""
    content = title + summary
    if code in content or name in content:
        # 針對長榮做嚴格的雜訊排除
        if name == '長榮':
            exclude_words = ['長榮航', '長榮航空', '長榮航太', '李長榮']
            if any(exclude in content for exclude in exclude_words):
                return False
        return True
    return False

def main():
    print(f"🚀 開始執行每日增量爬蟲: {datetime.now(taipei_tz).strftime('%Y-%m-%d %H:%M:%S')}")
    raw_news = fetch_today_news()
    filtered_data = []

    for news in raw_news:
        for code, name in TARGET_STOCKS.items():
            # 使用升級版的辨識函數過濾雜訊
            if is_target_news(news['title'], news['summary'], code, name):
                content = news['title'] + " " + news['summary']
                sentiment = get_finbert_score(content)
                # 使用升級版的時間對齊函數
                aligned_date = align_trading_date(news['publish_time'])

                filtered_data.append({
                    'Date': aligned_date.strftime('%Y-%m-%d'),
                    'ticker': f"{code}.TW",
                    'Daily_Sentiment': sentiment
                })

    if not filtered_data:
        print("今天沒有這五檔股票的新聞。")
        return

    # 聚合成每日單一分數
    df_today = pd.DataFrame(filtered_data)
    df_today_agg = df_today.groupby(['ticker', 'Date'])['Daily_Sentiment'].mean().reset_index()

    # 讀取原本的歷史 CSV，把今天的新資料貼在最下面
    if os.path.exists(CSV_FILE):
        df_history = pd.read_csv(CSV_FILE)
        df_combined = pd.concat([df_history, df_today_agg], ignore_index=True)
        # 去除重複（如果同一天不小心跑了兩次，以最新的為主）
        df_combined = df_combined.drop_duplicates(subset=['ticker', 'Date'], keep='last')
    else:
        df_combined = df_today_agg

    df_combined.to_csv(CSV_FILE, index=False, encoding='utf-8-sig')
    print(f"✅ 成功將今日資料寫入 {CSV_FILE}！")

if __name__ == "__main__":
    main()