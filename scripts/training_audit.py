"""Read-only training integrity checks; optional isolated, synthetic TensorFlow probe.

No command here trains a research candidate, selects a model, edits a source
snapshot, or rewrites a historical result. The fold manifest reconstructs the
current implementation; it cannot establish that missing old predictions were
generated by that implementation.
"""
