def _digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def notebook_function(path, name, namespace):
    """Extract one function without executing notebook I/O or training cells."""
    notebook = json.loads(Path(path).read_text(encoding="utf-8"))
    for cell in notebook["cells"]:
        if cell.get("cell_type") != "code":
            continue
        try:
            tree = ast.parse("".join(cell["source"]))
        except SyntaxError:
            continue
        for item in tree.body:
            if isinstance(item, ast.FunctionDef) and item.name == name:
                exec(compile(ast.Module(body=[item], type_ignores=[]), str(path), "exec"), namespace)
                return namespace[name]
    raise ValueError(f"Notebook function not found: {name}")


def scaler_future_shock_probe():
    """An extreme change after training must not change training inputs/scaler."""
    dates = pd.bdate_range("2020-01-01", periods=600)
    namespace = {"np": np, "pd": pd, "MinMaxScaler": MinMaxScaler,
                 "SEQ_LENGTH": 10, "VALIDATION_DAYS": 60, "MIN_TRAIN_SAMPLES": 252}
    prepare = notebook_function(ROOT / "notebooks/444_baseline.ipynb",
                                "prepare_univariate_windows", namespace)
    prices = pd.Series(np.linspace(100, 200, len(dates)), index=dates)
    control = prepare(prices, 150)
    shocked = prices.copy()
    shocked.iloc[control["train_end"]:] *= 10000
    changed = prepare(shocked, 150)
    np.testing.assert_array_equal(control["scaler"].data_max_, changed["scaler"].data_max_)
    np.testing.assert_array_equal(control["X_train"], changed["X_train"])
    if not control["train_dates"].max() < control["val_dates"].min() < control["test_dates"].min():
        raise AssertionError("444 temporal split order failed")

    features = ["Close", "MA20", "RSI_14", "MACD_Hist", "Market_Vol_20d", "Daily_Sentiment"]
    frame = pd.DataFrame({name: np.linspace(i + 1, i + 10, len(dates))
                          for i, name in enumerate(features)}, index=dates)
    frame["Target_Date"] = pd.Series(dates, index=dates).shift(-1)
    frame["Target_Next_Return"] = np.linspace(-5, 5, len(dates))
    frame.loc[dates[-1], "Target_Next_Return"] = np.nan
    frame["Risk_Threshold_Pct"] = 20
    namespace = {"np": np, "pd": pd, "MinMaxScaler": MinMaxScaler, "FEATURES": features,
                 "TIME_STEP": 10, "MIN_TRAIN_SAMPLES": 252,
                 "TARGET_DATES": dates[-150:], "VALIDATION_TARGET_DATES": dates[-210:-150]}
    prepare = notebook_function(ROOT / "notebooks/555_multivariate.ipynb", "make_windows", namespace)
    control = prepare(frame)
    shocked = frame.copy()
    first_validation_signal = dates.get_loc(namespace["VALIDATION_TARGET_DATES"][0]) - 1
    shocked.iloc[first_validation_signal:, :len(features)] *= 10000
    changed = prepare(shocked)
    np.testing.assert_array_equal(control["scaler"].data_max_, changed["scaler"].data_max_)
    np.testing.assert_array_equal(control["X_train"], changed["X_train"])
    if not control["train_dates"].max() < control["val_dates"].min() < control["test_dates"].min():
        raise AssertionError("555 temporal split order failed")
    return {"444": {"scaler_unchanged": True, "training_inputs_unchanged": True},
            "legacy_555": {"scaler_unchanged": True, "training_inputs_unchanged": True},
            "historical_news_availability_certified": False}


def fold_manifest(include_indices=False):
    from experiments.horizon_experiment import (
        LABEL_GAP, TIME_STEP, build_folds, feature_mask, load_context, usable_positions,
    )
    panel, frames, _risk, one, five, _excess = load_context()
    positions = usable_positions(panel.index, feature_mask(frames), one, five)
    folds = build_folds(positions)
    rows, seen_test = [], set()
    for number, fold in enumerate(folds, 1):
        if fold["train"][-1] + LABEL_GAP >= fold["val"][0]:
            raise AssertionError("Training labels cross validation boundary")
        if fold["val"][-1] + LABEL_GAP >= fold["test"][0]:
            raise AssertionError("Validation labels cross test boundary")
        test_positions = set(int(value) for value in fold["test"])
        if seen_test & test_positions:
            raise AssertionError("Duplicate test signals across folds")
        seen_test |= test_positions
        summary = {"fold": number}
        for name in ("train", "val", "test"):
            selected = np.asarray(fold[name], dtype=int)
            summary[name] = {
                "signals": int(len(selected)),
                "first_signal": str(panel.index[selected[0]].date()),
                "last_signal": str(panel.index[selected[-1]].date()),
                "last_label_end": str(panel.index[selected[-1] + LABEL_GAP].date()),
                "first_position": int(selected[0]), "last_position": int(selected[-1]),
                "positions_sha256": hashlib.sha256(selected.astype("<i8").tobytes()).hexdigest(),
            }
            if include_indices:
                summary[name]["positions"] = selected.tolist()
        rolling = fold["train"][-756:]
        input_rows = np.unique(np.concatenate([
            np.arange(int(position) - TIME_STEP + 1, int(position) + 1) for position in rolling
        ]))
        summary["rolling_756"] = {
            "feasible": bool(len(rolling) == 756), "definition": "usable training signal/label count",
            "signals": int(len(rolling)),
            "input_rows": int(len(input_rows)),
            "input_rows_if_consecutive": int(len(rolling) + TIME_STEP - 1),
            "first_input": str(panel.index[rolling[0] - TIME_STEP + 1].date()),
            "last_input": str(panel.index[rolling[-1]].date()),
        }
        rows.append(summary)
    return {"status": "current_source_reconstruction_not_original_execution_proof",
            "label": "100*(close[i+6]/close[i+1]-1)", "label_gap_sessions": LABEL_GAP,
            "fold_count": len(folds), "duplicate_test_signals": 0,
            "adjacent_training_overlap": "intentional expanding/rolling history",
            "folds": rows}


def optimizer_probe():
    """Exercise two independent fits and one carried-weight fit on real TF."""
    for name in ("TF_NUM_INTRAOP_THREADS", "TF_NUM_INTEROP_THREADS",
                 "TW_LSTM_INTRA_THREADS", "TW_LSTM_INTER_THREADS"):
        os.environ.setdefault(name, "1")
    os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
    from experiments.v2 import v28

    saved = {name: getattr(v28, name) for name in ("EPOCHS", "BATCH_SIZE", "PATIENCE")}
    v28.EPOCHS, v28.BATCH_SIZE, v28.PATIENCE = 2, 8, 1
    try:
        fitter = v28.Fitter()
        rng = np.random.default_rng(42)
        inputs = rng.normal(size=(24, v28.TIME_STEP, 2)).astype(np.float32)
        target = (inputs[:, -1, 0] + 0.25 * inputs[:, -1, 1] + 2).astype(np.float32)
        key, model = fitter._model(1, 3, 2)
        initial = [item.copy() for item in fitter.initial[key]]
        rows, previous_optimizer, carried = [], None, None
        for name, previous in (("first_independent", None), ("second_independent", None),
                               ("carried_weights_fresh_optimizer", "carry")):
            previous = carried if previous == "carry" else previous
            before = initial if previous is None else previous
            model, history, _elapsed = fitter.fit(inputs[:16], target[:16], inputs[16:], target[16:],
                                                 layers=1, units=3, previous=previous)
            delta = float(np.sqrt(sum(np.square(a - b).sum()
                                      for a, b in zip(before, model.get_weights()))))
            restored_validation_loss = float(np.mean(np.square(
                model(inputs[16:], training=False).numpy().ravel() - target[16:])))
            best_validation_loss = float(min(history.history["val_loss"]))
            learning_rate = float(model.optimizer.learning_rate)
            iterations = int(model.optimizer.iterations)
            expected_iterations = int(len(history.history["loss"]) * 2)
            if not np.isclose(learning_rate, v28.LEARNING_RATE) or delta <= 1e-8:
                raise AssertionError("A fit has a zero/wrong learning rate or unchanged model weights")
            if model.optimizer is previous_optimizer or iterations != expected_iterations:
                raise AssertionError("Optimizer state leaked across fits")
            if not np.isclose(restored_validation_loss, best_validation_loss, rtol=1e-5, atol=1e-6):
                raise AssertionError("Early stopping did not restore the best validation weights")
            rows.append({"fit": name, "learning_rate": learning_rate, "weight_l2_change": delta,
                         "optimizer_iterations": iterations, "fresh_optimizer": True,
                         "best_validation_loss": best_validation_loss,
                         "restored_validation_loss": restored_validation_loss})
            previous_optimizer = model.optimizer
            carried = [item.copy() for item in model.get_weights()]
        return {"tensorflow": fitter.tf.__version__, "synthetic_only": True, "fits": rows,
                "historical_results_retrained": False}
    finally:
        for name, value in saved.items():
            setattr(v28, name, value)


def frozen_prediction_replay(base_ref="b62034e4fa850933a632c8db6321b309ebad85f9"):
    """Compare retained-source/current TF inference with published forecasts.

    Load the retained Fitter class without executing its research runner. Both
    networks receive the same immutable NPZ weights and model-card scaler. No
    fit, model-bundle update, signal publication, or canonical write is made.
    This explicitly audits a proposed source change; it does not bypass the
    production bundle guard to generate live signals.
    """
    from experiments.risk_experiment import FEATURES, SEED, TICKERS, build_frames, load_panel, load_sentiment
    from experiments.v2 import v28

    retained_source = subprocess.check_output(
        ["git", "show", f"{base_ref}:experiments/v2/v28.py"], cwd=ROOT, text=True)
    parsed = ast.parse(retained_source)
    retained_class = next(item for item in parsed.body if isinstance(item, ast.ClassDef) and item.name == "Fitter")
    namespace = {"np": np, "TIME_STEP": v28.TIME_STEP, "SEED": SEED, "LEARNING_RATE": v28.LEARNING_RATE}
    exec(compile(ast.Module(body=[retained_class], type_ignores=[]), "retained_v28_Fitter", "exec"), namespace)
    old_fitter, new_fitter = namespace["Fitter"](), v28.Fitter()
    base = ROOT / "experiments/results/v2/v211"
    card_path, weights_path = base / "weights/model_card.json", base / "weights/weights.npz"
    card = json.loads(card_path.read_text(encoding="utf-8"))
    if card["features"] != list(FEATURES) or card["time_step"] != v28.TIME_STEP:
        raise AssertionError("Frozen feature order or sequence length changed")
    panel = load_panel(base / "market/prices.csv")
    sentiment = load_sentiment(base / "market/sentiment.csv", panel.index)
    frames, _risk = build_frames(panel, sentiment)
    rows, scaler_errors = [], {}
    train = np.asarray([panel.index.get_loc(pd.Timestamp(day)) for day in card["train_dates"]], dtype=int)
    train_rows = np.unique(np.concatenate([
        np.arange(position - v28.TIME_STEP + 1, position + 1) for position in train
    ]))
    with np.load(weights_path, allow_pickle=False) as store:
        for ticker in TICKERS:
            state = card["scalers"][ticker]
            raw = frames[ticker][list(FEATURES)].to_numpy(dtype=float)
            fitted = MinMaxScaler().fit(raw[train_rows])
            scaler_errors[ticker] = max(float(np.max(np.abs(getattr(fitted, name + "_") - state[name])))
                                        for name in ("data_min", "data_max", "scale", "min"))
            if scaler_errors[ticker] > 1e-12:
                raise AssertionError("Frozen scaler does not match its training input rows")
            loaded = [store[f"{ticker}_{i}"] for i in range(card["weight_counts"][ticker])]
            _, old_model = old_fitter._model(2, 50, len(FEATURES))
            _, new_model = new_fitter._model(2, 50, len(FEATURES))
            old_model.set_weights(loaded)
            new_model.set_weights(loaded)
            for day in ("2026-11-05", "2026-11-06", "2026-11-09"):
                path = base / "daily" / f"{day}.csv"
                if not path.is_file():
                    continue
                recorded = pd.read_csv(path).set_index("Ticker")
                position = int(panel.index.get_loc(pd.Timestamp(day)))
                window = raw[position - v28.TIME_STEP + 1:position + 1]
                scaled = (window * state["scale"] + state["min"]).astype(np.float32)[None, ...]
                original = float(old_model(scaled, training=False).numpy().ravel()[0])
                current = float(new_model(scaled, training=False).numpy().ravel()[0])
                saved = float(recorded.loc[ticker, "Predicted_Return_Pct"])
                if abs(current - saved) > 1e-6 or abs(current - original) > 1e-9:
                    raise AssertionError("Frozen prediction replay differs beyond tolerance")
                rows.append({"signal_date": day, "ticker": ticker, "retained_source_prediction": original,
                             "current_source_prediction": current, "published_prediction": saved,
                             "source_change_delta_percentage_points": abs(current - original),
                             "published_delta_percentage_points": abs(current - saved)})
    return {"method": "retained/current Keras networks; direct inference on immutable NPZ and scaler",
            "retained_ref": base_ref, "retained_v28_sha256": hashlib.sha256(retained_source.encode()).hexdigest(),
            "current_v28_sha256": _digest(ROOT / "experiments/v2/v28.py"),
            "weight_sha256": _digest(weights_path), "card_sha256": _digest(card_path),
            "prices_sha256": _digest(base / "market/prices.csv"),
            "sentiment_sha256": _digest(base / "market/sentiment.csv"),
            "tensorflow": new_fitter.tf.__version__, "prediction_rows": rows,
            "scaler_max_absolute_errors": scaler_errors,
            "maximum_source_change_delta_percentage_points": max(row["source_change_delta_percentage_points"] for row in rows),
            "maximum_published_delta_percentage_points": max(row["published_delta_percentage_points"] for row in rows),
            "production_bundle_modified": False, "trained_or_published": False}


def audit(include_indices=False, probe=False, replay=False):
    legacy_required = ("predictions.csv", "schedule_predictions.csv", "schedule_cost.csv", "fixed_predictions.csv")
    missing = [str(Path("experiments/results/v2/v28") / name) for name in legacy_required
               if not (ROOT / "experiments/results/v2/v28" / name).is_file()]
    weights = ROOT / "models/model_555_v2/weights/weights.npz"
    card_path = weights.with_name("model_card.json")
    card = json.loads(card_path.read_text(encoding="utf-8"))
    price_dates = pd.DatetimeIndex(sorted(pd.to_datetime(pd.read_csv(
        ROOT / "experiments/results/v2/v211/market/prices.csv")["Date"]).unique()))
    train_last = price_dates.get_loc(pd.Timestamp(card["train_end"]))
    early_last = price_dates.get_loc(pd.Timestamp(card["early_stop_end"]))
    if price_dates[train_last + 6] >= pd.Timestamp(card["early_stop_start"]):
        raise AssertionError("Frozen training labels overlap early stopping")
    if price_dates[early_last + 6] > pd.Timestamp(card["data_through"]):
        raise AssertionError("Frozen early-stopping labels were not mature at freeze")
    report = {
        "audit_scope": "training_integrity_not_all_130_questions",
        "source_sha256": {name: _digest(ROOT / name) for name in (
            "experiments/v2/v28.py", "experiments/v2/v29.py", "experiments/horizon_experiment.py",
            "notebooks/444_baseline.ipynb", "notebooks/555_multivariate.ipynb")},
        "future_shock": scaler_future_shock_probe(),
        "walk_forward": fold_manifest(include_indices),
        "frozen_bundle": {"weight_sha256": _digest(weights), "card_sha256": _digest(card_path),
                          "features": card["features"], "time_step": card["time_step"],
                          "train_label_count": len(card["train_dates"]),
                          "last_train_label_end": str(price_dates[train_last + 6].date()),
                          "early_stop_start": card["early_stop_start"],
                          "last_early_stop_label_end": str(price_dates[early_last + 6].date()),
                          "data_through": card["data_through"], "modified": False},
        "missing_legacy_exports": missing,
        "limitations": ["Historical research was repeatedly inspected and is exploratory.",
                        "Missing original exports prevent exact reconstruction of all historical V2 comparisons.",
                        "Corrected runnable source does not correct already-published historical figures.",
                        "Scalers/splits passing does not establish historical news point-in-time availability.",
                        "Hardware/software differences can change retraining outcomes; frozen inference is separately checked."],
    }
    if probe:
        report["optimizer_probe"] = optimizer_probe()
    if replay:
        report["frozen_prediction_replay"] = frozen_prediction_replay()
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--include-indices", action="store_true")
    parser.add_argument("--probe", action="store_true", help="Run a small synthetic TensorFlow fit probe")
    parser.add_argument("--frozen-replay", action="store_true", help="Compare retained/current frozen inference without production writes")
    args = parser.parse_args()
    print(json.dumps(audit(args.include_indices, args.probe, args.frozen_replay), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
